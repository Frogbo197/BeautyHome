<?php
namespace App\Service;

class RecommendationService
{
    /*
    |--------------------------------------------------------------------------
    | DINH DƯỠNG
    |--------------------------------------------------------------------------
    */

    public function recommendNutrition(
        float $bmi,
        ?string $goal,
        ?string $diet
    ): array {

        $foods = [];

        $goal = strtolower(
            trim($goal ?? '')
        );

        $diet = strtolower(
            trim($diet ?? '')
        );

        /*
        |--------------------------------------------------------------------------
        | BMI THẤP
        |--------------------------------------------------------------------------
        */

        if ($bmi < 18.5) {

            $foods[] =
                'Ức gà';

            $foods[] =
                'Trứng';

            $foods[] =
                'Sữa';

            $foods[] =
                'Cơm';

            $foods[] =
                'Chuối';
        }

        /*
        |--------------------------------------------------------------------------
        | BMI CAO
        |--------------------------------------------------------------------------
        */

        elseif ($bmi >= 25) {

            $foods[] =
                'Yến mạch';

            $foods[] =
                'Salad';

            $foods[] =
                'Cá hồi';

            $foods[] =
                'Khoai lang';

            $foods[] =
                'Rau xanh';
        }

        /*
        |--------------------------------------------------------------------------
        | BÌNH THƯỜNG
        |--------------------------------------------------------------------------
        */

        else {

            $foods[] =
                'Cơm gà';

            $foods[] =
                'Trái cây';

            $foods[] =
                'Sữa chua';
        }

        /*
        |--------------------------------------------------------------------------
        | GOAL
        |--------------------------------------------------------------------------
        */

        if (
            str_contains(
                $goal,
                'giảm cân'
            )
        ) {

            $foods[] =
                'Ức gà luộc';

            $foods[] =
                'Rau củ';
        }

        if (
            str_contains(
                $goal,
                'tăng cơ'
            )
        ) {

            $foods[] =
                'Bò';

            $foods[] =
                'Whey protein';
        }

        /*
        |--------------------------------------------------------------------------
        | CHẾ ĐỘ ĂN
        |--------------------------------------------------------------------------
        */

        if (
            str_contains(
                $diet,
                'eat clean'
            )
        ) {

            $foods[] =
                'Granola';

            $foods[] =
                'Sữa hạt';
        }

        return array_unique($foods);
    }

    /*
    |--------------------------------------------------------------------------
    | LUYỆN TẬP
    |--------------------------------------------------------------------------
    */

    public function recommendWorkout(
        float $bmi,
        ?string $goal,
        ?string $activityLevel
    ): array {

        $workouts = [];

        $goal = strtolower(
            trim($goal ?? '')
        );

        $activityLevel = strtolower(
            trim($activityLevel ?? '')
        );

        /*
        |--------------------------------------------------------------------------
        | BMI THẤP
        |--------------------------------------------------------------------------
        */

        if ($bmi < 18.5) {

            $workouts[] =
                'Gym tăng cơ';

            $workouts[] =
                'Resistance training';
        }

        /*
        |--------------------------------------------------------------------------
        | BMI CAO
        |--------------------------------------------------------------------------
        */

        elseif ($bmi >= 25) {

            $workouts[] =
                'Cardio';

            $workouts[] =
                'Đi bộ';

            $workouts[] =
                'Đạp xe';
        }

        /*
        |--------------------------------------------------------------------------
        | BÌNH THƯỜNG
        |--------------------------------------------------------------------------
        */

        else {

            $workouts[] =
                'Jogging';

            $workouts[] =
                'Gym nhẹ';
        }

        /*
        |--------------------------------------------------------------------------
        | GOAL
        |--------------------------------------------------------------------------
        */

        if (
            str_contains(
                $goal,
                'giảm cân'
            )
        ) {

            $workouts[] =
                'HIIT';

            $workouts[] =
                'Chạy bộ';
        }

        if (
            str_contains(
                $goal,
                'tăng cơ'
            )
        ) {

            $workouts[] =
                'Push day';

            $workouts[] =
                'Leg day';
        }

        /*
        |--------------------------------------------------------------------------
        | ÍT VẬN ĐỘNG
        |--------------------------------------------------------------------------
        */

        if (
            str_contains(
                $activityLevel,
                'thấp'
            )
        ) {

            $workouts[] =
                'Đi bộ 15 phút';
        }

        return array_unique(
            $workouts
        );
    }
}

